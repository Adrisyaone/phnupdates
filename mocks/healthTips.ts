export function getDailyTip(ncds: string[]): HealthTip {
  const today = new Date();
  const dayOfYear = Math.floor(
    (today.getTime() - new Date(today.getFullYear(), 0, 0).getTime()) / 86400000
  );

  let relevantTips: HealthTip[];
  if (ncds.length === 0) {
    relevantTips = ALL_HEALTH_TIPS;
  } else {
    const conditionTips = ALL_HEALTH_TIPS.filter(
      t => ncds.includes(t.category) || t.category === 'general'
    );
    relevantTips = conditionTips.length > 0 ? conditionTips : ALL_HEALTH_TIPS;
  }

  // Create a seeded index that's different from the previous simple modulo.
  const seedParts = [today.getFullYear(), today.getMonth() + 1, today.getDate(), ncds.slice().sort().join(',')];
  const seed = seedParts.join('-');

  // djb2 hash
  let hash = 5381;
  for (let i = 0; i < seed.length; i += 1) {
    hash = ((hash << 5) + hash) + seed.charCodeAt(i);
    hash = hash & 0xffffffff;
  }

  const index = Math.abs(hash) % relevantTips.length;
  return relevantTips[index];
}

export function getTipsForCategory(category: string): HealthTip[] {
  if (category === 'all') return ALL_HEALTH_TIPS;
  return ALL_HEALTH_TIPS.filter(t => t.category === category);
}

